export function translateGenre(name, lang) {
  if (!name) return '';
  const code = ((typeof lang === 'string' && lang) || getDisplayLanguage() || 'en').toLowerCase();
  if (GENRE_TRANSLATIONS[name] && GENRE_TRANSLATIONS[name][code]) {
    return GENRE_TRANSLATIONS[name][code];
  }
  // Fallback case-insensitive match
  const lower = name.toLowerCase().trim();
  for (const [key, map] of Object.entries(GENRE_TRANSLATIONS)) {
    if (key.toLowerCase() === lower && map[code]) return map[code];
  }
  // User/dynamic stored translations in localStorage
  try {
    const dynamicKey = 'jellio_genre_translations_' + code;
    const stored = window.localStorage.getItem(dynamicKey);
    if (stored) {
      const parsed = JSON.parse(stored);
      if (parsed && parsed[name]) return parsed[name];
    }
  } catch (_) {}
  return name;
}

export function getBadgeName(badgeOrId, fallback) {
  if (!badgeOrId) return fallback || '';
  const id = typeof badgeOrId === 'string' ? badgeOrId : (badgeOrId.Id || badgeOrId.BadgeId || '');
  const defaultName = (typeof badgeOrId === 'object' && (badgeOrId.Name || badgeOrId.BadgeName)) || fallback || id;
  const key = 'badge_name_' + id.toLowerCase().replace(/-/g, '_');
  return t(key, null, defaultName);
}

