export function getDisplayLanguage() {
  try {
    const saved = window.localStorage.getItem(STORAGE_KEY);
    if (saved && STRINGS[saved]) return saved;
  } catch (err) {
    // Ignore localStorage access failures
  }
  return 'en';
}

export function setDisplayLanguage(lang) {
  const code = (lang || '').toLowerCase();
  const valid = STRINGS[code] ? code : 'en';
  try {
    window.localStorage.setItem(STORAGE_KEY, valid);
  } catch (err) {
    // Ignore localStorage failure
  }
  window.dispatchEvent(new CustomEvent(EVENT_NAME, { detail: { language: valid } }));
  return valid;
}

export function getAcceptLanguageHeader() {
  const lang = getDisplayLanguage();
  if (lang === 'de') return 'de-DE, de;q=0.9, en;q=0.8';
  if (lang === 'es') return 'es-ES, es;q=0.9, en;q=0.8';
  if (lang === 'pl') return 'pl-PL, pl;q=0.9, en;q=0.8';
  return 'en-US, en;q=0.9';
}

export function t(key, params) {
  const lang = getDisplayLanguage();
  const dict = STRINGS[lang] || STRINGS.en;
  let text = dict[key] || STRINGS.en[key] || key;
  if (params && typeof params === 'object') {
    Object.keys(params).forEach(function (paramKey) {
      text = text.replace(new RegExp('\\{' + paramKey + '\\}', 'g'), params[paramKey]);
    });
  }
  return text;
}
